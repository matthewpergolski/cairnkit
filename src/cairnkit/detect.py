"""Find the toolchain of a project, for the dev preset. Read only.

A tool counts as found when its lock file or config is in the project root or
one folder below it. A check (ruff, biome) counts as run only when a CI file or
a git hook that git runs calls it: directly, through a script that it names, or
through a package.json script. A config file alone does not make a rule
enforced, and neither does a hook file that git does not run.
"""

from __future__ import annotations

import json
import os
import re
import tomllib
from dataclasses import dataclass
from pathlib import Path

from cairnkit.paths import run_git

SKIP = {"node_modules", "dist", "build", "venv", "__pycache__", "target", "vendor"}
PINS = (".python-version", ".nvmrc", ".node-version", ".bun-version", ".tool-versions")
OTHER_LOCKS = ("package-lock.json", "pnpm-lock.yaml", "yarn.lock")
CI_GLOBS = (".github/workflows/*.yml", ".github/workflows/*.yaml", ".gitlab-ci.yml")
# Hook files that git runs only when they are set up (see _entries).
HOOK_GLOBS = (".githooks/*", ".husky/*", ".pre-commit-config.yaml", "lefthook.yml", ".lefthook.yml")
PRE_COMMIT_SHIM = re.compile(r"hook-impl|generated by pre-commit", re.I)
LEFTHOOK_SHIM = re.compile(r"\blefthook\b")
NO_SHIM = "is not installed as a git hook"
SCRIPT_REF = re.compile(r"(?<![\w/.-])(?:\./)?([\w.-]+(?:/[\w.-]+)+\.(?:py|sh|mjs|cjs|js|ts))")
PACKAGE_RUN = re.compile(r"\b(?:bun|npm|pnpm|yarn)\s+(?:run\s+)?([\w:-]+)")
TOOLS = {"ruff": re.compile(r"\bruff\b"), "biome": re.compile(r"\bbiome\b|@biomejs/biome")}
RUFF_DEP = re.compile(r"""["']ruff\s*(?:[<>=~!;\[]|["'])""")
MAX_BYTES = 200_000
NAMES = ("uv", "ruff", "ruff-run", "bun", "other-lockfile", "biome", "biome-run", "pins")


@dataclass(frozen=True)
class Finding:
    found: bool
    reason: str


def _folders(root: Path) -> list[Path]:
    out = [root]
    try:
        children = sorted(root.iterdir())
    except OSError:
        return out
    out += [
        p
        for p in children
        if p.is_dir() and not p.is_symlink() and not p.name.startswith(".") and p.name not in SKIP
    ]
    return out


def _rel(root: Path, path: Path) -> str:
    try:
        return path.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        return str(path)


def _read(path: Path) -> str:
    try:
        if path.stat().st_size > MAX_BYTES:
            return ""
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def _files(root: Path, name: str) -> list[Path]:
    return [f / name for f in _folders(root) if (f / name).is_file()]


def _pyproject(path: Path) -> dict:
    try:
        return tomllib.loads(_read(path))
    except tomllib.TOMLDecodeError:
        return {}


def _found(paths: list[str], what: str = "") -> Finding:
    if not paths:
        return Finding(False, f"no {what}" if what else "not found")
    return Finding(True, ", ".join(paths))


def _uv(root: Path) -> Finding:
    found = [_rel(root, p) for p in _files(root, "uv.lock")]
    for path in _files(root, "pyproject.toml"):
        if "uv" in _pyproject(path).get("tool", {}):
            found.append(f"[tool.uv] in {_rel(root, path)}")
    return _found(found, "uv.lock or [tool.uv]")


def _ruff(root: Path) -> Finding:
    found = [_rel(root, p) for n in ("ruff.toml", ".ruff.toml") for p in _files(root, n)]
    deps = []
    for path in _files(root, "pyproject.toml"):
        if "ruff" in _pyproject(path).get("tool", {}):
            found.append(_rel(root, path))
        elif RUFF_DEP.search(_read(path)):
            deps.append(_rel(root, path))
    parts = [f"ruff config in {', '.join(found)}"] if found else []
    parts += [f"ruff in the dependencies of {', '.join(deps)}"] if deps else []
    return Finding(bool(parts), "; ".join(parts) or "no ruff config")


def _hook_files(folder: Path | None) -> list[Path]:
    if folder is None or not folder.is_dir():
        return []
    return [p for p in sorted(folder.iterdir()) if p.is_file() and not p.name.endswith(".sample")]


def _entries(root: Path) -> tuple[list[Path], list[tuple[Path, str]]]:
    """Files that git or CI runs, and hook files that git does not run, with why."""
    runs = [p for g in CI_GLOBS for p in sorted(root.glob(g)) if p.is_file()]
    idle: list[tuple[Path, str]] = []
    folder, how = None, "this folder is not a git repo"
    if run_git(root, "rev-parse", "--git-dir") is not None:
        setting = run_git(root, "config", "--get", "core.hooksPath")
        if setting:
            folder, how = root / Path(setting).expanduser(), f"core.hooksPath is {setting}"
            common = run_git(root, "rev-parse", "--path-format=absolute", "--git-common-dir")
            idle += [(p, how) for p in _hook_files(Path(common) / "hooks" if common else None)]
        else:
            path = run_git(root, "rev-parse", "--path-format=absolute", "--git-path", "hooks")
            folder, how = (Path(path) if path else None), "core.hooksPath is not set"
    active = []
    for path in _hook_files(folder):
        if os.access(path, os.X_OK):
            active.append(path)
        else:
            idle.append((path, "it is not executable"))
    shims = "\n".join(_read(p) for p in active)
    husky = folder is not None and folder.resolve() == (root / ".husky" / "_").resolve()
    seen = {p.resolve() for p in active} | {p.resolve() for p, _ in idle}
    for pattern in HOOK_GLOBS:
        for path in sorted(root.glob(pattern)):
            if not path.is_file() or path.name.endswith(".sample") or path.resolve() in seen:
                continue
            if folder is None:
                why = how
            elif path.name == ".pre-commit-config.yaml":
                why = None if PRE_COMMIT_SHIM.search(shims) else f"pre-commit {NO_SHIM}"
            elif path.name.endswith("lefthook.yml"):
                why = None if LEFTHOOK_SHIM.search(shims) else f"lefthook {NO_SHIM}"
            elif path.parent.name == ".husky":
                why = None if husky else how
            else:
                why = how
            if why is None:
                runs.append(path)
            else:
                idle.append((path, why))
    return runs + active, idle


def _package_scripts(root: Path) -> dict[str, tuple[str, str]]:
    """{script name: (package.json path, command)} for each package.json found."""
    out: dict[str, tuple[str, str]] = {}
    for path in _files(root, "package.json"):
        try:
            scripts = json.loads(_read(path) or "{}").get("scripts", {})
        except (json.JSONDecodeError, AttributeError):
            continue
        if isinstance(scripts, dict):
            for name, command in scripts.items():
                if isinstance(command, str):
                    out.setdefault(name, (_rel(root, path), command))
    return out


def _calls(root: Path, entry: Path, pattern: re.Pattern, scripts: dict) -> str | None:
    """The chain from entry to the tool, following one script and package scripts."""
    texts = [(_rel(root, entry), _read(entry))]
    for ref in SCRIPT_REF.findall(texts[0][1]):
        target = (root / ref).resolve()
        if target.is_file() and target.is_relative_to(root.resolve()):
            texts.append((f"{texts[0][0]} -> {ref}", _read(target)))
    for chain, text in list(texts):
        for name in PACKAGE_RUN.findall(text):
            if name in scripts:
                package, command = scripts[name]
                texts.append((f"{chain} -> {package} script {name}", command))
    return next((chain for chain, text in texts if pattern.search(text)), None)


def _runs(root: Path, tool: str) -> Finding:
    """Does a CI file, or a hook that git runs, run the tool?"""
    pattern = TOOLS[tool]
    scripts = _package_scripts(root)
    runs, idle = _entries(root)
    for entry in runs:
        chain = _calls(root, entry, pattern, scripts)
        if chain:
            return Finding(True, f"run by {chain}")
    for entry, why in idle:
        chain = _calls(root, entry, pattern, scripts)
        if chain:
            return Finding(False, f"found in {chain}, but {why}, so git does not run it")
    return Finding(False, f"no hook or CI runs {tool}")


def detect(root: Path) -> dict[str, Finding]:
    """Return the findings by name (see NAMES)."""
    bun = [_rel(root, p) for n in ("bun.lock", "bun.lockb") for p in _files(root, n)]
    others = [_rel(root, p) for n in OTHER_LOCKS for p in _files(root, n)]
    biome = [_rel(root, p) for n in ("biome.json", "biome.jsonc") for p in _files(root, n)]
    pins = [_rel(root, p) for n in PINS for p in _files(root, n)]
    found = {
        "uv": _uv(root),
        "ruff": _ruff(root),
        "bun": _found(bun, "bun.lock"),
        "other-lockfile": _found([] if bun else others, "npm, pnpm or yarn lock file without Bun"),
        "biome": _found(biome, "biome.json"),
        "pins": _found(pins, "version pin file"),
    }
    found["ruff-run"] = _runs(root, "ruff") if found["ruff"].found else Finding(False, "no ruff")
    found["biome-run"] = (
        _runs(root, "biome") if found["biome"].found else Finding(False, "no biome")
    )
    return found
