"""`memory hooks install` and `memory hooks uninstall`."""

from __future__ import annotations

import contextlib
import json
import os
import re
import sys
from pathlib import Path

from cairnkit import adapters, githook, instructions, markers, refresh, rules
from cairnkit.ignore import drop_lines, is_tracked
from cairnkit.init import can_link, ensure_all_linked, is_linked
from cairnkit.memory import Memory, MemoryMissing
from cairnkit.paths import (
    GIT_FOLDER_REFUSAL,
    LINK_NAME,
    Project,
    inside_git_folder,
    resolve_memory_dir,
    run_git,
)

SEEN_FILE = ".agents-seen.json"
# Grok also runs these tools' project hooks, and each hook must run once.
GROK_RUNS_HOOKS_OF = frozenset({"claude", "cursor"})


def guard_patterns(project: Project, flag: str | None) -> githook.GuardPatterns:
    try:
        config = Memory.open(project, flag).config
    except MemoryMissing:
        return githook.GuardPatterns(
            list(githook.DEFAULT_GUARD_PATTERNS), list(githook.DEFAULT_IDENTITY_PATTERNS)
        )
    return githook.GuardPatterns(config["guard_patterns"], config["guard_identity_patterns"])


def _sync_rules(project: Project, flag: str | None, dry_run: bool) -> list[str]:
    """Keep the default rule's enforced_by true to the installed commit-msg guard."""
    if not project.is_git or dry_run:
        return []
    try:
        memory = Memory.open(project, flag)
    except MemoryMissing:
        return []
    return rules.sync_guard(memory, githook.guard_installed(project))


# Tests turn this off, so that a test of something else does not read the real machine's tools.
INSTALL_ON_INIT = True
# The guard refuses "Generated by ..." and "Co-authored-by: Cursor ...", so a rule asks for it
# only when it forbids attribution and names AI. "Keep license attribution in NOTICE" does not.
ATTRIBUTION = re.compile(r"(?i)\b(?:attribution|co-?author|generated[- ](?:with|by))")
AI_WORDS = re.compile(
    r"(?i)\b(?:ai|llm|gpt|agents?|claude|anthropic|openai|chatgpt|codex|copilot|cursor|gemini|grok|opus|sonnet|haiku|fable)\b"
)
FORBIDS = re.compile(r"(?i)\b(?:never|no|not|don't|avoid|without|remove|forbid|ban)\b")
TOOL_ADDED_GUARD = "cairnkit.guardaddedbytool"


def _rule_asks_for_guard(project: Project, flag: str | None) -> bool | None:
    """Does an active rule forbid AI attribution? None when there is no memory to ask."""
    try:
        memory = Memory.open(project, flag)
    except MemoryMissing:
        return None
    return any(
        s.get("kind") == "rule"
        and s.get("status") == "active"
        and all(word.search(s["text"]) for word in (ATTRIBUTION, AI_WORDS, FORBIDS))
        for s in memory.states.values()
    )


def _tool_added_guard(project: Project) -> bool:
    return run_git(project.root, "config", "--local", "--get", TOOL_ADDED_GUARD) == "true"


def _remember_guard(project: Project, tool_added: bool) -> None:
    """The hook text cannot hold this, because `memory init --refresh` rewrites it."""
    if tool_added:
        run_git(project.root, "config", "--local", TOOL_ADDED_GUARD, "true")
    else:
        run_git(project.root, "config", "--local", "--unset", TOOL_ADDED_GUARD)


def _plan_guard(
    project: Project, flag: str | None, guard: str | None, git_hook: bool
) -> tuple[str | None, bool, bool]:
    """Return (guard to install, the tool added it, remove the guard).

    An explicit --commit-msg-guard stays for good. A rule adds a guard, and when the
    last such rule ends, the guard that the tool added goes. Any other guard stays.
    """
    if guard or not git_hook or not project.is_git:
        return guard, False, False
    asked = _rule_asks_for_guard(project, flag)
    added = _tool_added_guard(project)
    if asked:
        return "local", added or not githook.guard_installed(project), False
    return None, False, asked is False and added


def _install_guard(
    project: Project, flag: str | None, guard: str | None, tool_added: bool, remove: bool, dry: bool
) -> list[str]:
    if not project.is_git or not (guard or remove):
        return []
    if remove:
        steps = githook.uninstall(project, "commit-msg", dry)
    else:
        body = githook.guard_body(guard_patterns(project, flag))
        steps = githook.install(project, "commit-msg", body, dry)
    if not dry:
        _remember_guard(project, tool_added)
    return steps


def _install_push_check(project: Project, flag: str | None, on: bool, dry: bool) -> list[str]:
    body = githook.pre_push_body(guard_patterns(project, flag) if on else None)
    return githook.install(project, "pre-push", body, dry)


def githook_connected(project: Project) -> bool:
    """True when the memory git hooks run here."""
    return project.is_git and githook.is_running(project, "pre-commit")


def sync_guard_only(project: Project, flag: str | None) -> None:
    """A rule added after setup gets its check now, with no second setup step."""
    guard, tool_added, remove = _plan_guard(project, flag, None, True)
    steps = _install_guard(project, flag, guard, tool_added, remove, False)
    if guard or remove:
        steps += _install_push_check(project, flag, bool(guard), False)
    for step in steps:
        print(step)
    for step in _sync_rules(project, flag, False):
        print(step)


def _print_summary(
    project: Project, names: list[str], guard: str | None, git_hook: bool, steps: list[str]
) -> None:
    """Two or three lines. `--verbose` or `memory hooks install` prints each step."""
    agents = [name for name in names if name != "generic"]
    print(f"Agents connected: {', '.join(agents)}." if agents else "No agent tool found here.")
    hook_skips = tuple(f"skip {hook}" for hook in githook.ALL_HOOKS)
    if project.is_git and git_hook and not any(s.startswith(hook_skips) for s in steps):
        extra = ", and a commit-message check" if guard else ""
        folder = os.path.relpath(githook.hooks_dir(project), project.root)
        print(f"Git hooks installed in {folder}{extra}. They are not shared.")
    for step in steps:
        if step.startswith(("skip", "note")):
            print(step)
    if "codex" in names and adapters.codex_in_use():
        print(adapters.CODEX_TRUST)
    if "generic" in names:
        print("For any other agent, run: memory hooks install --agent generic")


def _connect(project: Project, name: str, targets: list[Path], dry_run: bool) -> list[str]:
    steps = adapters.apply(project, name, install=True, dry_run=dry_run, checkouts=targets)
    if name in GROK_RUNS_HOOKS_OF:
        steps += adapters.apply(project, "grok", install=False, dry_run=dry_run)
    return steps


def _seen(memdir: Path) -> list[str] | None:
    """The tools that were on the machine at setup or at the last sync. None: no record."""
    try:
        data = json.loads((memdir / SEEN_FILE).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return data if isinstance(data, list) else None


def _remember_seen(memdir: Path, names: list[str]) -> None:
    merged = sorted({*(_seen(memdir) or []), *names} - {"generic"})
    with contextlib.suppress(OSError):
        (memdir / SEEN_FILE).write_text(json.dumps(merged) + "\n", encoding="utf-8")


def connect_new_tools(project: Project, flag: str | None) -> None:
    """Connect a tool that appeared since the last look. Silent, and it never raises.

    A tool in the record stays as the developer left it, so a removed adapter or a tool
    left out of `memory hooks install --agent NAME` does not come back. On the quiet path
    this reads one small file and looks on PATH, and it runs no program.
    """
    try:
        memdir, _ = resolve_memory_dir(project, flag)
        if not (memdir / "facts").is_dir():
            return
        seen = _seen(memdir)
        if seen is None:
            # A memory from before the record: what is connected counts as chosen.
            seen = [
                name
                for name, adapter in adapters.ADAPTERS.items()
                if adapters.holds_ours(project.main_root / adapter.rel)
            ]
            if not seen:
                return
            _remember_seen(memdir, seen)
        new = [n for n in adapters.detect(project) if n != "generic" and n not in seen]
        if not new:
            return
        targets = [c for c in project.checkouts if is_linked(c, memdir)]
        for name in new:
            # A file to fix stays out of the record, so the next look tries it again.
            with contextlib.suppress(adapters.BadConfig):
                _connect(project, name, targets, False)
                _remember_seen(memdir, [name])
    except Exception:
        return


def run_install(
    project: Project,
    agent: str,
    dry_run: bool,
    git_hook: bool,
    guard: str | None,
    flag: str | None = None,
    quiet: bool = False,
    this_checkout: bool = False,
) -> int:
    if inside_git_folder(Path.cwd()):
        print(GIT_FOLDER_REFUSAL.format(cwd=Path.cwd()), file=sys.stderr)
        return 1
    names = adapters.detect(project) if agent == "auto" else [agent]
    guard, tool_added, remove_guard = _plan_guard(project, flag, guard, git_hook)
    hooks = ["pre-commit", "post-checkout", "pre-push", "post-merge"] if git_hook else []
    hooks += ["commit-msg"] if guard == "local" or remove_guard else []
    broken = githook.broken_paths(project, hooks)
    if broken:
        for path in broken:
            print(markers.broken_message(path, "memory hooks install"))
        return 1
    steps: list[str] = []
    memdir, _ = resolve_memory_dir(project, flag)
    # Link every checkout that can be linked before writing agent config into it.
    if not dry_run:
        steps += ensure_all_linked(project, flag)
    else:
        for checkout in project.checkouts:
            if can_link(project, checkout, memdir):
                target = os.path.relpath(memdir, checkout)
                steps.append(f"link {checkout / LINK_NAME} -> {target}")
    has_memory = (memdir / "facts").is_dir()
    if has_memory:
        # Real install: only linked checkouts. Dry-run: already linked or healable.
        targets = [
            c
            for c in project.checkouts
            if is_linked(c, memdir) or (dry_run and can_link(project, c, memdir))
        ]
        if not dry_run:
            for checkout in project.checkouts:
                if checkout not in targets:
                    steps.append(
                        f"skip {checkout}: not linked to {memdir}; "
                        f"run `memory init --path {memdir}` from there first"
                    )
    else:
        # No project memory yet: never put stop-hook config into an unlinked worktree.
        targets = [project.main_root]
    if this_checkout:
        targets = [c for c in targets if c == project.root]
        steps += [
            f"note not connected: {c}. To connect it, run `memory hooks install` there."
            for c in project.checkouts
            if c != project.root
        ]
    bad: set[str] = set()
    for name in names:
        if name == "generic":
            continue
        try:
            steps += _connect(project, name, targets, dry_run)
        except adapters.BadConfig as exc:
            bad.add(name)
            steps.append(f"skip {name}: {exc}")
    names = [name for name in names if name not in bad]
    if has_memory and not dry_run:
        # A file to fix stays out of the record, so the next look tries it again.
        _remember_seen(memdir, [n for n in [*names, *adapters.detect(project)] if n not in bad])
    if project.is_git and git_hook:
        steps += githook.install(project, "pre-commit", githook.pre_commit_body(), dry_run)
        steps += githook.install(project, "post-checkout", githook.post_checkout_body(), dry_run)
        steps += githook.install(project, "post-merge", githook.post_merge_body(), dry_run)
        steps += githook.uninstall(project, "post-commit", dry_run)  # 0.3.1 mined commits here
    guarded = bool(guard) or (
        project.is_git and githook.guard_installed(project) and not remove_guard
    )
    steps += _install_guard(project, flag, guard, tool_added, remove_guard, dry_run)
    if project.is_git and (git_hook or guard):
        steps += _install_push_check(project, flag, guarded, dry_run)
    steps += _sync_rules(project, flag, dry_run)
    if dry_run:
        print("Dry run: nothing will change.")
    else:
        refresh.record(project, flag)
    code = 1 if bad and agent != "auto" else 0
    if quiet:
        _print_summary(project, names, guard, git_hook, steps)
        return code
    for step in steps:
        plain = step.startswith(("skip", "note"))
        print(("would " if dry_run and not plain else "") + step)
    print(f"Agents: {', '.join(names)}")
    for name in names:
        if name == "generic":
            print(adapters.generic_help())
        if name in adapters.EXPERIMENTAL:
            print(f"Note: the {name} adapter is experimental. Check it once in the tool.")
        if name == "codex" and (agent != "auto" or adapters.codex_in_use()):
            print("Codex runs project hooks only in a trusted project. Review them in /hooks.")
    if not steps:
        print("Already installed. Nothing to do.")
    return code


def _take_back_blocks(project: Project, dry_run: bool) -> list[str]:
    """The rules blocks that `--write-instructions` wrote. A tracked file never changes."""
    memdir, _ = resolve_memory_dir(project)
    steps = []
    for checkout in project.checkouts:
        for path in refresh.block_paths(project, memdir):
            if not path.is_relative_to(checkout):
                continue
            if is_tracked(project, path.relative_to(checkout).as_posix(), checkout):
                continue
            result = instructions.take_back_block(path, checkout, dry_run)
            if result == "removed":
                steps.append(f"remove the rules block from {path}")
            elif result == "broken":
                steps.append(f"skip {markers.broken_message(path, 'memory hooks uninstall')}")
    return steps


def _take_back_exclude(project: Project) -> list[str]:
    """The exclude lines of files that are now gone. The link stays, so its lines stay."""
    rels = [*(adapter.rel for adapter in adapters.ADAPTERS.values()), *refresh.BLOCK_FILES]
    return drop_lines(
        project, [r for r in rels if not any(os.path.lexists(c / r) for c in project.checkouts)]
    )


def run_uninstall(project: Project, dry_run: bool) -> int:
    steps: list[str] = []
    bad = False
    for name in adapters.ADAPTERS:
        try:
            steps += adapters.apply(project, name, install=False, dry_run=dry_run)
        except adapters.BadConfig as exc:
            bad = True
            steps.append(f"skip {name}: {exc}")
    steps += _take_back_blocks(project, dry_run)
    if project.is_git:
        for hook in githook.ALL_HOOKS:
            steps += githook.uninstall(project, hook, dry_run)
        if not dry_run:
            _remember_guard(project, False)
        steps += _sync_rules(project, None, dry_run)
    if not dry_run:
        steps += _take_back_exclude(project)
    for step in steps:
        plain = step.startswith(("skip", "note"))
        print(("would " if dry_run and not plain else "") + step)
    if not steps:
        print("No memory hooks found. Nothing to do.")
    return 1 if bad else 0
