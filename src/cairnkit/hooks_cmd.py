"""`memory hooks install` and `memory hooks uninstall`."""

from __future__ import annotations

import os
import re

from cairnkit import adapters, githook, markers, refresh, rules
from cairnkit.init import can_link, ensure_all_linked, is_linked
from cairnkit.memory import Memory, MemoryMissing
from cairnkit.paths import LINK_NAME, Project, resolve_memory_dir, run_git


def guard_patterns(project: Project, flag: str | None) -> list[str]:
    try:
        return Memory.open(project, flag).config["guard_patterns"]
    except MemoryMissing:
        return list(githook.DEFAULT_GUARD_PATTERNS)


def _sync_rules(project: Project, flag: str | None, dry_run: bool) -> list[str]:
    """Keep the default rule's enforced_by true to the installed commit-msg guard."""
    if not project.is_git or dry_run:
        return []
    try:
        memory = Memory.open(project, flag)
    except MemoryMissing:
        return []
    return rules.sync_guard(memory, githook.guard_installed(project))


# Tests turn this off, so that a test of something else does not read the real machine's tools.
INSTALL_ON_INIT = True
# The guard refuses "Generated by ..." and "Co-authored-by: Cursor ...", so a rule asks for it
# only when it forbids attribution and names AI. "Keep license attribution in NOTICE" does not.
ATTRIBUTION = re.compile(r"(?i)\b(?:attribution|co-?author|generated[- ](?:with|by))")
AI_WORDS = re.compile(
    r"(?i)\b(?:ai|llm|gpt|agents?|claude|anthropic|openai|chatgpt|codex|copilot|cursor|gemini|grok)\b"
)
FORBIDS = re.compile(r"(?i)\b(?:never|no|not|don't|avoid|without|remove|forbid|ban)\b")
TOOL_ADDED_GUARD = "cairnkit.guardaddedbytool"


def _rule_asks_for_guard(project: Project, flag: str | None) -> bool | None:
    """Does an active rule forbid AI attribution? None when there is no memory to ask."""
    try:
        memory = Memory.open(project, flag)
    except MemoryMissing:
        return None
    return any(
        s.get("kind") == "rule"
        and s.get("status") == "active"
        and all(word.search(s["text"]) for word in (ATTRIBUTION, AI_WORDS, FORBIDS))
        for s in memory.states.values()
    )


def _tool_added_guard(project: Project) -> bool:
    return run_git(project.root, "config", "--local", "--get", TOOL_ADDED_GUARD) == "true"


def _remember_guard(project: Project, tool_added: bool) -> None:
    """The hook text cannot hold this, because `memory init --refresh` rewrites it."""
    if tool_added:
        run_git(project.root, "config", "--local", TOOL_ADDED_GUARD, "true")
    else:
        run_git(project.root, "config", "--local", "--unset", TOOL_ADDED_GUARD)


def _plan_guard(
    project: Project, flag: str | None, guard: str | None, git_hook: bool
) -> tuple[str | None, bool, bool]:
    """Return (guard to install, the tool added it, remove the guard).

    An explicit --commit-msg-guard stays for good. A rule adds a guard, and when the
    last such rule ends, the guard that the tool added goes. Any other guard stays.
    """
    if guard or not git_hook or not project.is_git:
        return guard, False, False
    asked = _rule_asks_for_guard(project, flag)
    added = _tool_added_guard(project)
    if asked:
        return "local", added or not githook.guard_installed(project), False
    return None, False, asked is False and added


def _install_guard(
    project: Project, flag: str | None, guard: str | None, tool_added: bool, remove: bool, dry: bool
) -> list[str]:
    if not project.is_git or not (guard or remove):
        return []
    if remove:
        steps = githook.uninstall(project, "commit-msg", dry)
    else:
        body = githook.guard_body(guard_patterns(project, flag))
        steps = githook.install(project, "commit-msg", body, dry)
    if not dry:
        _remember_guard(project, tool_added)
    return steps


def githook_connected(project: Project) -> bool:
    """True when the memory git hooks run here."""
    folder = githook.hooks_dir(project) if project.is_git else None
    path = folder / "pre-commit" if folder else None
    return bool(path and path.is_file() and githook.holds_block(path.read_text(errors="replace")))


def sync_guard_only(project: Project, flag: str | None) -> None:
    """A rule added after setup gets its check now, with no second setup step."""
    guard, tool_added, remove = _plan_guard(project, flag, None, True)
    for step in _install_guard(project, flag, guard, tool_added, remove, False):
        print(step)
    for step in _sync_rules(project, flag, False):
        print(step)


def _print_summary(
    project: Project, names: list[str], guard: str | None, git_hook: bool, steps: list[str]
) -> None:
    """Two or three lines. `--verbose` or `memory hooks install` prints each step."""
    agents = [name for name in names if name != "generic"]
    print(f"Agents connected: {', '.join(agents)}." if agents else "No agent tool found here.")
    if project.is_git and git_hook:
        extra = ", and a commit-message check" if guard else ""
        print(f"Git hooks installed in .git/hooks{extra}. They are not shared.")
    for step in steps:
        if step.startswith(("skip", "note")):
            print(step)
    if "codex" in names:
        print("Codex: approve the hooks once with /hooks, because Codex asks for trust itself.")
    if "generic" in names:
        print("For any other agent, run: memory hooks install --agent generic")


def run_install(
    project: Project,
    agent: str,
    dry_run: bool,
    git_hook: bool,
    guard: str | None,
    flag: str | None = None,
    quiet: bool = False,
) -> int:
    names = adapters.detect(project) if agent == "auto" else [agent]
    guard, tool_added, remove_guard = _plan_guard(project, flag, guard, git_hook)
    hooks = ["pre-commit", "post-checkout", "pre-push", "post-merge"] if git_hook else []
    hooks += ["commit-msg"] if guard == "local" or remove_guard else []
    broken = githook.broken_paths(project, hooks)
    if broken:
        for path in broken:
            print(markers.broken_message(path, "memory hooks install"))
        return 1
    steps: list[str] = []
    memdir, _ = resolve_memory_dir(project, flag)
    # Link every checkout that can be linked before writing agent config into it.
    if not dry_run:
        steps += ensure_all_linked(project, flag)
    else:
        for checkout in project.checkouts:
            if can_link(project, checkout, memdir):
                target = os.path.relpath(memdir, checkout)
                steps.append(f"link {checkout / LINK_NAME} -> {target}")
    has_memory = (memdir / "facts").is_dir()
    if has_memory:
        # Real install: only linked checkouts. Dry-run: already linked or healable.
        targets = [
            c
            for c in project.checkouts
            if is_linked(c, memdir) or (dry_run and can_link(project, c, memdir))
        ]
        if not dry_run:
            for checkout in project.checkouts:
                if checkout not in targets:
                    steps.append(
                        f"skip {checkout}: not linked to {memdir}; "
                        f"run `memory init --path {memdir}` from there first"
                    )
    else:
        # No project memory yet: never put stop-hook config into an unlinked worktree.
        targets = [project.main_root]
    try:
        for name in names:
            if name != "generic":
                steps += adapters.apply(
                    project, name, install=True, dry_run=dry_run, checkouts=targets
                )
    except adapters.BadConfig as exc:
        print(f"error: {exc}")
        return 1
    if project.is_git and git_hook:
        steps += githook.install(project, "pre-commit", githook.pre_commit_body(), dry_run)
        steps += githook.install(project, "post-checkout", githook.post_checkout_body(), dry_run)
        steps += githook.install(project, "pre-push", githook.pre_push_body(), dry_run)
        steps += githook.install(project, "post-merge", githook.post_merge_body(), dry_run)
        steps += githook.uninstall(project, "post-commit", dry_run)  # 0.3.1 mined commits here
    steps += _install_guard(project, flag, guard, tool_added, remove_guard, dry_run)
    steps += _sync_rules(project, flag, dry_run)
    if dry_run:
        print("Dry run: nothing will change.")
    else:
        refresh.record(project, flag)
    if quiet:
        _print_summary(project, names, guard, git_hook, steps)
        return 0
    for step in steps:
        plain = step.startswith(("skip", "note"))
        print(("would " if dry_run and not plain else "") + step)
    print(f"Agents: {', '.join(names)}")
    for name in names:
        if name == "generic":
            print(adapters.generic_help())
        if name in adapters.EXPERIMENTAL:
            print(f"Note: the {name} adapter is experimental. Check it once in the tool.")
        if name == "codex":
            print("Codex runs project hooks only in a trusted project. Review them in /hooks.")
    if not steps:
        print("Already installed. Nothing to do.")
    return 0


def run_uninstall(project: Project, dry_run: bool) -> int:
    steps: list[str] = []
    try:
        for name in adapters.ADAPTERS:
            steps += adapters.apply(project, name, install=False, dry_run=dry_run)
    except adapters.BadConfig as exc:
        print(f"error: {exc}")
        return 1
    if project.is_git:
        for hook in (
            "pre-commit",
            "post-checkout",
            "pre-push",
            "post-merge",
            "post-commit",
            "commit-msg",
        ):
            steps += githook.uninstall(project, hook, dry_run)
        if not dry_run:
            _remember_guard(project, False)
        steps += _sync_rules(project, None, dry_run)
    for step in steps:
        plain = step.startswith(("skip", "note"))
        print(("would " if dry_run and not plain else "") + step)
    if not steps:
        print("No memory hooks found. Nothing to do.")
    return 0
